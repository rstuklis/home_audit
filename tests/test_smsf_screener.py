class TestGrossedUpYield:
    def test_fully_franked_at_30pct(self):
        gross, credit = ss.grossed_up_yield(4.0, 100.0)
        assert gross == pytest.approx(4.0 * (1 + 0.3 / 0.7))
        assert credit == pytest.approx(gross - 4.0)

    def test_unfranked_is_unchanged(self):
        assert ss.grossed_up_yield(4.0, 0.0) == (4.0, 0.0)

    def test_half_franked(self):
        gross, _ = ss.grossed_up_yield(4.0, 50.0)
        assert gross == pytest.approx(4.0 + 4.0 * 0.5 * 0.3 / 0.7)

    @pytest.mark.parametrize("franking", [-1, 101])
    def test_rejects_bad_franking(self, franking):
        with pytest.raises(ss.ScreenerError):
            ss.grossed_up_yield(4.0, franking)

    def test_rejects_bad_tax_rate(self):
        with pytest.raises(ss.ScreenerError):
            ss.grossed_up_yield(4.0, 100.0, tax_rate=1.0)


