def _rows(start, closes, volume=1000):
    return [{"date": start + timedelta(days=i), "close": c, "volume": volume} for i, c in enumerate(closes)]


class TestComputeMetrics:
    def test_flat_series_has_zero_vol_and_drawdown(self):
        rows = _rows(date(2025, 1, 1), [50.0] * 300)
        m = ss.compute_metrics(rows, [], date(2025, 12, 31))
        assert m["has_prices"]
        assert m["vol_pct"] == pytest.approx(0.0)
        assert m["mdd_pct"] == pytest.approx(0.0)
        assert m["adv_aud"] == pytest.approx(50_000.0)
        assert m["cash_yield_pct"] == 0.0
        assert m["ttm_dist_count"] == 0

    def test_drawdown_is_worst_fall_from_peak(self):
        rows = _rows(date(2025, 1, 1), [100, 120, 90, 110, 60, 80])
        m = ss.compute_metrics(rows, [], date(2025, 1, 6))
        assert m["mdd_pct"] == pytest.approx(50.0)   # 120 -> 60

    def test_rows_after_as_of_are_ignored(self):
        rows = _rows(date(2025, 1, 1), [100, 100, 100, 1])
        m = ss.compute_metrics(rows, [], date(2025, 1, 3))
        assert m["last_price"] == 100 and m["mdd_pct"] == 0.0

    def test_no_rows_on_or_before_as_of(self):
        rows = _rows(date(2025, 6, 1), [100, 100])
        assert ss.compute_metrics(rows, [], date(2025, 1, 1)) == {"has_prices": False}

    def test_ttm_window_is_half_open(self):
        as_of = date(2026, 3, 1)
        rows = _rows(as_of - timedelta(days=400), [100.0] * 401)
        dists = [
            {"date": as_of - timedelta(days=365), "amount": 5.0},   # exactly a year ago: out
            {"date": as_of - timedelta(days=364), "amount": 1.0},   # in
            {"date": as_of, "amount": 2.0},                          # on as-of: in
            {"date": as_of + timedelta(days=1), "amount": 7.0},     # future: out
        ]
        m = ss.compute_metrics(rows, dists, as_of)
        assert m["ttm_dist_per_unit"] == pytest.approx(3.0)
        assert m["ttm_dist_count"] == 2
        assert m["cash_yield_pct"] == pytest.approx(3.0)

    def test_total_return_uses_price_a_year_ago_plus_distributions(self):
        as_of = date(2026, 3, 1)
        closes = [100.0] * 366 + [110.0] * 35
        rows = _rows(as_of - timedelta(days=400), closes)
        m = ss.compute_metrics(rows, [{"date": as_of, "amount": 4.0}], as_of)
        assert m["total_return_1y_pct"] == pytest.approx(14.0)

    def test_short_history_leaves_vol_unknown(self):
        rows = _rows(date(2026, 8, 1), [100 + i for i in range(10)])
        m = ss.compute_metrics(rows, [], date(2026, 8, 10))
        assert m["vol_pct"] is None and m["adv_aud"] is None
        assert m["mdd_pct"] == pytest.approx(0.0)

    def test_volatility_is_annualised_stdev_of_log_returns(self):
        import math
        import statistics
        closes = [100.0]
        for i in range(60):
            closes.append(closes[-1] * (1.01 if i % 2 else 0.99))
        rows = _rows(date(2026, 1, 1), closes)
        m = ss.compute_metrics(rows, [], date(2026, 3, 1))
        rets = [math.log(b / a) for a, b in zip(closes, closes[1:])]
        assert m["vol_pct"] == pytest.approx(statistics.stdev(rets) * math.sqrt(252) * 100)


