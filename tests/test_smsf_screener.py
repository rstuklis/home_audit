class _Index:
    def __init__(self, d):
        self._d = d

    def date(self):
        return self._d


class _Series(dict):
    def items(self):
        return [(_Index(k), v) for k, v in dict.items(self)]


class _Frame:
    def __init__(self, rows):
        self._rows = rows
        self.columns = ["Close", "Volume", "Dividends"]

    def __len__(self):
        return len(self._rows)

    def iterrows(self):
        for d, row in self._rows:
            yield _Index(d), row

    def __getitem__(self, key):
        assert key == "Dividends"
        return _Series({d: row["Dividends"] for d, row in self._rows})


